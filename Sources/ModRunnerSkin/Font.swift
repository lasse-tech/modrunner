public extension Canvas {

    /// Draws text with the top-left of the first cell at (x, y). `scale`
    /// multiplies the pixels rather than resampling anything, which is the only
    /// honest way to enlarge a bitmap face.
    mutating func text(_ string: String, at x: Int, _ y: Int,
                       _ colour: Colour, scale: Int = 1) {
        var penX = x
        for character in string {
            let glyph = Font.glyph(for: character)
            for (row, bits) in glyph.enumerated() {
                guard bits != 0 else { continue }
                for column in 0..<8 where (bits >> (7 - column)) & 1 == 1 {
                    if scale == 1 {
                        set(penX + column, y + row, colour)
                    } else {
                        fill(Rect(penX + column * scale, y + row * scale, scale, scale), colour)
                    }
                }
            }
            penX += Font.cellWidth * scale
        }
    }

    /// Draws text clipped to a width, cutting it off rather than overflowing
    /// into whatever panel comes next.
    mutating func text(_ string: String, at x: Int, _ y: Int, _ colour: Colour,
                       scale: Int = 1, maxWidth: Int) {
        let fits = Swift.max(0, maxWidth / (Font.cellWidth * scale))
        text(String(string.prefix(fits)), at: x, y, colour, scale: scale)
    }
}
