    /// Anything with no glyph: a hollow box, the way a terminal admits it does
    /// not know a character rather than dropping it silently.
    private static let missing: [UInt8] = [0x00, 0x78, 0x48, 0x48, 0x48, 0x78, 0x00, 0x00]

    public static func glyph(for character: Character) -> [UInt8] {
        if let scalar = character.unicodeScalars.first,
           character.unicodeScalars.count == 1,
           scalar.value >= 32, scalar.value <= 126 {
            return printable[Int(scalar.value) - 32]
        }
        return extras[character] ?? missing
    }

    public static func width(of text: String, scale: Int = 1) -> Int {
        text.count * cellWidth * scale
    }
